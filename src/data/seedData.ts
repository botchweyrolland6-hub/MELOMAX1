export const INITIAL_TYRES: Tyre[] = RAW_USER_TYRES.map((item, index) => {
  const category = INITIAL_CATEGORIES.find(c => c.name === item.categoryName) || INITIAL_CATEGORIES[0];
  const tyreName = `Tyre ${item.size}`;
  const stock = (index % 7 === 0) ? 0 : (index % 4 === 0) ? Math.floor(Math.random() * 4) + 1 : Math.floor(Math.random() * 25) + 6;
  
  let status: Tyre['status'] = 'in_stock';
  if (stock === 0) status = 'out_of_stock';
  else if (stock <= 5) status = 'low_stock';

  // Use Pic 1 for first 70 tyres (index 0..69) and Pic 2 for remaining 100 tyres (index 70..169)
  const imageUrl = index < 70 ? '/tyre1.png' : '/tyre2.png';

  return {
    id: `tyre-${index + 1}`,
    name: tyreName,
    brand: 'MeloMax',
    model: 'Standard',
    size: item.size,
    category_id: category.id,
    category_name: category.name,
    price: item.price,
    stock_quantity: stock,
    description: `High performance ${category.name} tyre engineered for maximum durability, heat resistance, and superior wet & dry traction. Size: ${item.size}.`,
    image_url: imageUrl,
    status,
    created_at: new Date(Date.now() - index * 3600000).toISOString(),
    updated_at: new Date(Date.now() - index * 1800000).toISOString(),
  };
});

